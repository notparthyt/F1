import { schema, t, type SchemaType } from "@colyseus/schema";

export const LobbyPlayer = schema({
  name: t.string(),
  isHost: t.boolean(),
}, "LobbyPlayer");
export type LobbyPlayer = SchemaType<typeof LobbyPlayer>;

export const RacePlayer = schema({
  name: t.string(),
  isHost: t.boolean(),
  x: t.number(),
  y: t.number(),
  heading: t.number(),
  vx: t.number(),
  vy: t.number(),
  yawRate: t.number(),
  gear: t.number(),
  steer: t.number(),
  speed: t.number(),
  drs: t.number(),
  ersCharge: t.number(),
  ersDeploy: t.number(),
  compound: t.string(),
  lap: t.number(),
  progress: t.number(),
  position: t.number(),
  pitRequest: t.string(),
  pitPhase: t.string(),
  penaltySeconds: t.number(),
  trackLimitWarnings: t.number(),
  avatarX: t.number(),
  avatarY: t.number(),
  avatarHeading: t.number(),
  avatarSuit: t.number(),
  avatarEmote: t.string(),
  avatarMoving: t.boolean(),
  onFoot: t.boolean(),
  finished: t.boolean(),
  retired: t.boolean(),
  disqualified: t.boolean(),
  engineRpm: t.number(),
  engineShifting: t.boolean(),
  engineLimiter: t.boolean(),
  ax: t.number(),
  ay: t.number(),
  downforce: t.number(),
  tireWear0: t.number(),
  tireWear1: t.number(),
  tireWear2: t.number(),
  tireWear3: t.number(),
  tireSurfaceTemp0: t.number(),
  tireSurfaceTemp1: t.number(),
  tireSurfaceTemp2: t.number(),
  tireSurfaceTemp3: t.number(),
  tireCarcassTemp0: t.number(),
  tireCarcassTemp1: t.number(),
  tireCarcassTemp2: t.number(),
  tireCarcassTemp3: t.number(),
  tireSlipPower0: t.number(),
  tireSlipPower1: t.number(),
  tireSlipPower2: t.number(),
  tireSlipPower3: t.number(),
  ersDeployedLap: t.number(),
  ersHarvestedLap: t.number(),
  fuel: t.number(),
}, "RacePlayer");
export type RacePlayer = SchemaType<typeof RacePlayer>;

export const LobbySettings = schema({
  circuit: t.string(),
  laps: t.number(),
  mode: t.string(),
  qualifying: t.boolean(),
  retirements: t.boolean(),
  penalties: t.boolean(),
}, "LobbySettings");
export type LobbySettings = SchemaType<typeof LobbySettings>;

export const LobbyState = schema({
  code: t.string(),
  hostSessionId: t.string(),
  status: t.string(),
  settingsReady: t.boolean(),
  raceTime: t.number(),
  weatherRaining: t.boolean(),
  weatherIntensity: t.number(),
  weatherWetness: t.number(),
  yellowFlag: t.boolean(),
  yellowFlagRemaining: t.number(),
  safetyCarProgress: t.number(),
  safetyCarSpeed: t.number(),
  countdown: t.number(),
  phase: t.string(),
  settings: LobbySettings,
  players: t.map(LobbyPlayer),
  racePlayers: t.map(RacePlayer),
}, "LobbyState");
export type LobbyState = SchemaType<typeof LobbyState>;
